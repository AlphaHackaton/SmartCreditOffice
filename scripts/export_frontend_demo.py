"""Export public demo fixtures from the real domain; never an HTTP/OpenAPI schema."""
import json
import sys
from dataclasses import asdict, replace
from datetime import datetime, timedelta, timezone
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))

from app.domain.application_status import IN_PROGRESS, initial_event, replay, transition
from app.domain.enums import Actor, ApplicationStatus
from app.domain.scoring.engine import evaluate, simulate
from app.domain.scoring.policy import POLICY_V1
from app.domain.scoring.explain import hints
from app.domain.scoring.metrics import compute_metrics
from app.domain.serialization import canonical, result_to_json
from app.seed.personas import load_inputs, load_raw, load_request


def journey(outcome):
    start = datetime(2026, 10, 25, tzinfo=timezone.utc)
    events = [initial_event(Actor.CLIENT, start)]
    for index, status in enumerate((ApplicationStatus.SUBMITTED, ApplicationStatus.SCORING, outcome), 1):
        actor = Actor.CLIENT if index == 1 else Actor.SYSTEM
        events.append(transition(events[-1].to_status, status, actor, at=start + timedelta(seconds=index)))
    replay(events)
    return [{'from': e.from_status, 'to': e.to_status, 'actor': e.actor} for e in events]


def simulations(persona_id, result):
    req = load_request(persona_id)
    product = POLICY_V1.product(req.product_code)
    amounts = sorted({product.min_amount, req.amount, max(product.min_amount, (req.amount / 2 // POLICY_V1.amount_step) * POLICY_V1.amount_step), *(o.amount for o in result.offers)})
    terms = list(range(product.min_term, product.max_term + 1, POLICY_V1.term_step))
    rows = []
    for amount in amounts:
        for term in terms:
            value = simulate(load_inputs(persona_id), replace(req, amount=Decimal(amount), term_months=term), POLICY_V1)
            rows.append({'amount': str(amount), 'termMonths': term, 'outcome': value.predicted_outcome,
                         'requiresReview': value.requires_review, 'offers': canonical(value.offers),
                         'constraints': canonical(value.constraints), 'maxAmount': str(value.max_amount_for_term), 'headroom': str(value.headroom)})
    return {'amounts': [str(a) for a in amounts], 'terms': terms, 'rows': rows}


personas = []
for raw in load_raw()['personas']:
    result = evaluate(load_inputs(raw['id']), load_request(raw['id']), POLICY_V1)
    final = ApplicationStatus.UNDERWRITING if result.route.value == 'UNDERWRITING' else ApplicationStatus(result.recommendation.value)
    personas.append({
        'id': raw['id'], 'login': raw['login'], 'label': f"Демо {raw['login']} · ИНН {raw['company']['inn']}",
        'company': {'id': raw['id'], 'name': f"{'ИП' if raw['company']['legal_form'] == 'IP' else 'ООО'} · {raw['company']['inn']}", **raw['company']},
        'request': {**raw['request'], 'term_months': int(raw['request']['term_months'])},
        'journey': journey(final),
        'simulation': simulations(raw['id'], result),
        'decision': {
            'factors': [{'code': f.code, 'text': f.client_text, 'hint': f.hint, 'impact': f.impact} for f in result.factors],
            'offers': result_to_json(result)['offers'],
            'constraints': result_to_json(result)['constraints'],
            'binding': result.binding_constraint,
            'recommendations': list(hints(compute_metrics(load_inputs(raw['id'])), result, load_inputs(raw['id']), POLICY_V1).values()),
            'policyVersion': result.policy_version,
        },
    })
data = {
    'policyVersion': POLICY_V1.version,
    'products': [{**asdict(p), 'min_amount': str(p.min_amount), 'max_amount': str(p.max_amount), 'spread_pct': str(p.spread_pct)} for p in POLICY_V1.products],
    'amountStep': str(POLICY_V1.amount_step), 'termStep': POLICY_V1.term_step,
    'personas': personas, 'customJourney': journey(ApplicationStatus.UNDERWRITING),
    'signingEvents': {
        f'{src.value}_{dst.value}': {'from': e.from_status, 'to': e.to_status, 'actor': e.actor}
        for src, dst, actor in ((ApplicationStatus.SIGNING, ApplicationStatus.SIGNED, Actor.CLIENT), (ApplicationStatus.SIGNING, ApplicationStatus.EXPIRED, Actor.SYSTEM), (ApplicationStatus.SIGNED, ApplicationStatus.DISBURSED, Actor.SYSTEM))
        for e in [transition(src, dst, actor, at=datetime(2026, 10, 25, tzinfo=timezone.utc))]
    },
    'decisionEvents': {
        f'{src.value}_{dst.value}': {'from': e.from_status, 'to': e.to_status, 'actor': e.actor}
        for src in (ApplicationStatus.APPROVED, ApplicationStatus.COUNTER_OFFER)
        for dst, actor in ((ApplicationStatus.SIGNING, Actor.CLIENT), (ApplicationStatus.EXPIRED, Actor.SYSTEM))
        for e in [transition(src, dst, actor, at=datetime(2026, 10, 25, tzinfo=timezone.utc))]
    },
}
output = '// Generated by scripts/export_frontend_demo.py. Do not edit. Not an HTTP contract.\n'
output += 'export const DOMAIN_STATUSES = ' + json.dumps([s.value for s in ApplicationStatus]) + ' as const;\n'
output += 'export type ApplicationStatus = typeof DOMAIN_STATUSES[number];\n'
output += 'export const POLLING_STATUSES: readonly ApplicationStatus[] = ' + json.dumps(sorted(s.value for s in IN_PROGRESS)) + ';\n'
output += 'export const demoData = ' + json.dumps(data, ensure_ascii=False, indent=2) + ' as const;\n'
target = ROOT / 'frontend/src/demo/generated.ts'
target.parent.mkdir(parents=True, exist_ok=True)
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != output:
        raise SystemExit('Demo fixtures are stale. Run npm run gen:demo --prefix frontend')
    print('Demo fixtures match backend seed, policy and FSM')
else:
    target.write_text(output)
    print(f'Exported {len(personas)} personas, {len(POLICY_V1.products)} products, domain statuses and validated histories')
