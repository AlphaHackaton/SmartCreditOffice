"""Export public demo fixtures from the real domain; never an HTTP/OpenAPI schema."""
import json
import sys
from dataclasses import asdict
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))

from app.domain.application_status import IN_PROGRESS, initial_event, replay, transition
from app.domain.enums import Actor, ApplicationStatus
from app.domain.scoring.engine import evaluate
from app.domain.scoring.policy import POLICY_V1
from app.seed.personas import load_inputs, load_raw, load_request


def journey(outcome):
    start = datetime(2026, 10, 25, tzinfo=timezone.utc)
    events = [initial_event(Actor.CLIENT, start)]
    for index, status in enumerate((ApplicationStatus.SUBMITTED, ApplicationStatus.SCORING, outcome), 1):
        actor = Actor.CLIENT if index == 1 else Actor.SYSTEM
        events.append(transition(events[-1].to_status, status, actor, at=start + timedelta(seconds=index)))
    replay(events)
    return [{'from': e.from_status, 'to': e.to_status, 'actor': e.actor} for e in events]


personas = []
for raw in load_raw()['personas']:
    result = evaluate(load_inputs(raw['id']), load_request(raw['id']), POLICY_V1)
    final = ApplicationStatus.UNDERWRITING if result.route.value == 'UNDERWRITING' else ApplicationStatus(result.recommendation.value)
    personas.append({
        'id': raw['id'], 'login': raw['login'], 'label': f"Демо {raw['login']} · ИНН {raw['company']['inn']}",
        'company': {'id': raw['id'], 'name': f"{'ИП' if raw['company']['legal_form'] == 'IP' else 'ООО'} · {raw['company']['inn']}", **raw['company']},
        'request': {**raw['request'], 'term_months': int(raw['request']['term_months'])},
        'journey': journey(final),
    })
data = {
    'policyVersion': POLICY_V1.version,
    'products': [{**asdict(p), 'min_amount': str(p.min_amount), 'max_amount': str(p.max_amount), 'spread_pct': str(p.spread_pct)} for p in POLICY_V1.products],
    'amountStep': str(POLICY_V1.amount_step), 'termStep': POLICY_V1.term_step,
    'personas': personas, 'customJourney': journey(ApplicationStatus.UNDERWRITING),
}
output = '// Generated by scripts/export_frontend_demo.py. Do not edit. Not an HTTP contract.\n'
output += 'export const DOMAIN_STATUSES = ' + json.dumps([s.value for s in ApplicationStatus]) + ' as const;\n'
output += 'export type ApplicationStatus = typeof DOMAIN_STATUSES[number];\n'
output += 'export const POLLING_STATUSES: readonly ApplicationStatus[] = ' + json.dumps(sorted(s.value for s in IN_PROGRESS)) + ';\n'
output += 'export const demoData = ' + json.dumps(data, ensure_ascii=False, indent=2) + ' as const;\n'
target = ROOT / 'frontend/src/demo/generated.ts'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(output)
print(f'Exported {len(personas)} personas, {len(POLICY_V1.products)} products, domain statuses and validated histories')
