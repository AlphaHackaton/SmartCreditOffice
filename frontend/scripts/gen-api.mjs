import { readFile, mkdir, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

export const defaultInput = fileURLToPath(new URL('../../docs/openapi.json', import.meta.url));
export const defaultOutput = fileURLToPath(new URL('../src/api/schema.d.ts', import.meta.url));

export async function generateApi(input = defaultInput, output = defaultOutput) {
  let schema;
  try {
    schema = JSON.parse(await readFile(input, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') throw new Error('Нужен docs/openapi.json от Dev 2. Опубликуйте экспорт backend перед генерацией типов.');
    throw new Error(`Не удалось прочитать OpenAPI: ${error.message}`);
  }
  const result = '// This file is automatically generated from docs/openapi.json. Do not edit.\n' + astToString(await openapiTS(schema));
  await mkdir(dirname(output), { recursive: true });
  const temporary = `${output}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, result, { flag: 'wx' });
    await rename(temporary, output);
  } finally {
    await rm(temporary, { force: true });
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    await generateApi();
    console.log('Типы API созданы: src/api/schema.d.ts');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
